const DARK='https://basemaps.cartocdn.com/gl/dark-matter-gl-style/style.json';
const FALLBACK='https://tiles.openfreemap.org/styles/positron';
const mapEl=document.getElementById('map');
const map=new maplibregl.Map({container:'map',style:DARK,center:[104.29,52.29],zoom:11});
map.addControl(new maplibregl.NavigationControl({showCompass:false}),'top-left');
let fell=false;
map.on('error',()=>{
  if(!fell && !map.isStyleLoaded()){fell=true;mapEl.classList.add('light-tiles');map.setStyle(FALLBACK);}
});
const lngLat=s=>[s.ll[1],s.ll[0]];
const routeData=()=>({type:'Feature',geometry:{type:'LineString',coordinates:STOPS.map(lngLat)}});
function addRoute(){
  if(map.getSource('route'))return;
  map.addSource('route',{type:'geojson',data:routeData()});
  map.addLayer({id:'route',type:'line',source:'route',layout:{'line-cap':'round'},paint:{'line-color':'#e0793f','line-width':3,'line-dasharray':[2,2]}});
}
map.on('style.load',addRoute);
const fit=()=>{const b=new maplibregl.LngLatBounds();STOPS.forEach(s=>b.extend(lngLat(s)));map.fitBounds(b,{padding:50,duration:0});};
fit();

const box=document.getElementById('stops'),pins=[],markers=[],cards=[];
STOPS.forEach((s,i)=>{
  const el=document.createElement('div');el.className='pin';el.textContent=i+1;
  el.addEventListener('click',()=>cards[i].scrollIntoView({behavior:'smooth',block:'center'}));
  markers.push(new maplibregl.Marker({element:el}).setLngLat(lngLat(s)).addTo(map));pins.push(el);
  const c=document.createElement('article');
  c.className='stop';c.id='stop'+(i+1);
  c.innerHTML=`<div class="photo"><small>Фото: Википедия</small></div>
  <div class="body"><h2><span class="num">${i+1}</span>${s.t}</h2>
  <p class="facts">${s.f}</p><p>${s.d}</p>
  <div class="sig"><b>Значение:</b> ${s.s}</div>
  <p class="next">${i<STOPS.length-1?'➜ '+s.n:'★ '+s.n}</p></div>`;
  box.appendChild(c);cards.push(c);
  loadInfo(s.q).then(r=>{
    if(r.img)c.querySelector('.photo').style.backgroundImage=`url("${r.img}")`;
    // уточняем координаты по Википедии, только если они рядом с исходными
    if(r.lat!=null&&Math.abs(r.lat-s.ll[0])<.06&&Math.abs(r.lon-s.ll[1])<.06){
      s.ll=[r.lat,r.lon];markers[i].setLngLat(lngLat(s));
      const src=map.getSource('route');if(src)src.setData(routeData());
    }
  });
});

async function loadInfo(q){
  try{
    const u='https://ru.wikipedia.org/w/api.php?action=query&generator=search&gsrlimit=1&prop=pageimages|coordinates&piprop=thumbnail&pithumbsize=900&format=json&origin=*&gsrsearch='+encodeURIComponent(q);
    const j=await (await fetch(u)).json();
    const p=Object.values(j.query.pages)[0],co=p.coordinates&&p.coordinates[0];
    return {img:p.thumbnail&&p.thumbnail.source,lat:co?co.lat:null,lon:co?co.lon:null};
  }catch(e){return {};}
}

const io=new IntersectionObserver(es=>{
  es.forEach(e=>{if(e.isIntersecting){
    const i=cards.indexOf(e.target);
    cards.forEach((c,k)=>c.classList.toggle('active',k===i));
    pins.forEach((p,k)=>p.classList.toggle('on',k===i));
    map.flyTo({center:lngLat(STOPS[i]),zoom:i===STOPS.length-1?11:14,duration:900});
  }});
},{threshold:.6});
cards.forEach(c=>io.observe(c));
